const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const root = path.resolve(process.argv[2] || 'build');
const page = fs.readFileSync(path.join(root,'trading-journal','index.html'),'utf8');
const dom = new JSDOM(page,{runScripts:'dangerously'});
const document = dom.window.document;
assert.ok(page.includes('SYNTHETIC DEMONSTRATION'));
assert.equal(document.getElementById('trades').textContent,'40+');
assert.equal(document.getElementById('reasons').textContent,'70%');
assert.ok(document.getElementById('chart').textContent.includes('decision'));
const view=document.getElementById('view');view.value='mode_distribution';
view.dispatchEvent(new dom.window.Event('change'));
assert.ok(document.getElementById('chart').textContent.includes('local paper'));
assert.equal(document.querySelectorAll('script[src],iframe,img,link[rel="stylesheet"]').length,0);
assert.ok(page.includes("connect-src 'none'"));
const data=JSON.parse(document.getElementById('dataset').textContent);
assert.deepEqual(Object.keys(data).sort(),['context_coverage_percent','event_count_lower_bound','insight_schema_version','lifecycle_distribution','mode_distribution','reason_coverage_percent','sample','trade_intents_lower_bound']);
for(const forbidden of ['candidate_id','model_id','run_id','report_id','trade_id','order_id','fill_id','recorded_time','event_time','source_sha256','source_hash','close_window','synthetic-trade','synthetic-run','SECRET_ACCOUNT','C:/Users','fetch(','XMLHttpRequest','WebSocket']) assert.ok(!page.includes(forbidden),forbidden);
assert.ok(fs.existsSync(path.join(root,'index.html')));
assert.ok(fs.existsSync(path.join(root,'trading-lab','index.html')));
dom.window.close();
console.log('Journal: synthetic-only allowlisted data, offline controls, links and no private identifiers passed.');
